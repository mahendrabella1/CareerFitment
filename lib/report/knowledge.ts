/** Rough, monotonic "higher than X% of students" read from a 0–100 score. */
export const percentileOf = (score: number) => Math.max(5, Math.min(97, Math.round(score * 0.95)));

/** Per-dimension sub-trait bars, drawn from whatever breakdown data exists. */
export function subTraits(key: string, a: AssessmentSummary): { label: string; value: number }[] {
  const clean = (arr: { label: string; value: number }[]) =>
    arr.filter((x) => x.label && x.value > 0).slice(0, 8);
  switch (key) {
    // `a.themes` is the career-CLUSTER vector (A-H), not RIASEC interest - see
    // the same fix in categoryDeepDive. Read the real Holland scores instead.
    case "career_interest": {
      const riasec = (a.riasecScores ?? []).length ? a.riasecScores! : [];
      return riasec.length
        ? riasec.slice().sort((x, y) => y.score - x.score).map((r) => ({ label: r.name, value: r.score }))
        : clean((a.themes ?? []).map((t) => ({ label: t.title, value: t.score })));
    }
    // All 8 of Gardner's intelligences are always scored (shareRank divides a
    // fixed pool of points across all 8 - see scoring60.ts), so a 0 is a real
    // "measured zero pull toward this" result, not "no evidence." clean()'s
    // value>0 filter was silently dropping whichever of the 8 scored 0,
    // showing 6-7 instead of the full 8 - the "we have 8 things" bug.
    case "multiple_intelligence": return (a.topIntelligences ?? []).filter((x) => x.name).slice(0, 8).map((x) => ({ label: x.name, value: x.score }));
    // Always exactly the 4 VARK styles (both class 9-10's and 11-12's own
    // scoring always emit all 4, never a variable-length list) - same
    // reasoning as aptitude below: a 0 here is "measured zero pull toward
    // this style," real data, not "no evidence." clean()'s value>0 filter
    // was silently dropping whichever 1-2 of the 4 styles a student's
    // limited number of learning-style questions happened to score 0 on -
    // exactly the "I should see 4, only see 2" bug a user reported.
    case "learning_styles": return (a.learningStyles ?? []).filter((x) => x.name).slice(0, 8).map((x) => ({ label: x.name, value: x.score }));
    // All 6 motivator categories are always scored (same shareRank pattern as
    // MI above), so - same fix - don't drop genuine 0s.
    case "motivators": return (a.topValues ?? []).filter((x) => x.tag).slice(0, 8).map((x) => ({ label: x.tag, value: x.score }));
    // All 8 strength domains are always scored from the forced-choice bank -
    // same fix again.
    case "strengths": return (a.strengthsBreakdown ?? []).filter((x) => x.name).slice(0, 8).map((x) => ({ label: x.name, value: x.score }));
    // Every aptitude sub-area is always answered (fixed question counts per
    // area), so a 0 here means "got every question in that area wrong," a
    // real result worth showing - not "no evidence," which is what a 0
    // means for the other dimensions clean() filters out. Using clean()
    // here silently hid whichever sub-areas a student scored 0% on.
    case "aptitude": return (a.topAptitudes ?? []).filter((x) => x.skill).slice(0, 8).map((x) => ({ label: x.skill, value: x.score }));
    case "personality": return clean((a.topStrengths ?? []).map((x) => ({ label: x.subTraitName, value: x.normalizedScore })));
    // Show the standard 4-quadrant EQ model (mapped from the engine's 5
    // measured dimensions - see eiQuadrants) rather than the 5 raw, thinly
    // -measured single-question dimensions directly.
    case "emotional_intelligence": return eiQuadrants(a).filter((x) => x.label);
    default: return [];
  }
}

