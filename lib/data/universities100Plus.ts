export const getUniversitiesByCountry = (country: string): University[] => UNIVERSITIES_100_PLUS.filter(u => u.country === country);

export const searchUniversities = (query: string): University[] => {
  const lower = query.toLowerCase();
  return UNIVERSITIES_100_PLUS.filter(u =>
    u.name.toLowerCase().includes(lower) ||
    u.country.toLowerCase().includes(lower) ||
    u.programs.some(p => p.name.toLowerCase().includes(lower))
  );
};

export const getTopUniversities = (limit: number = 20): University[] =>
  [...UNIVERSITIES_100_PLUS].sort((a, b) => a.ranking.world_rank - b.ranking.world_rank).slice(0, limit);

